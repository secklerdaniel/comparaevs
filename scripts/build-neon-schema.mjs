// Schema do comparaevs no Neon — bem mais simples que livro-foto/gramaldo26:
// sem auth (o site não tem login), sem FK de verdade entre as tabelas (o
// Supabase original também não tinha — veiculo_id/patrocinador_id são
// referências soltas, conferido via information_schema antes de escrever
// isto), só 1 função (registrar_clique_faixa) que FICA DE FORA de propósito
// — ela grava em `faixa_cliques`, tabela do sistema de faixa cruzada
// compartilhado entre os apps da casa, fora do escopo de só migrar o
// comparaevs.
//
// pbe_veiculos_eletricos/pbe_motos_eletricas têm colunas com maiúscula
// (Categoria, Marca, Uber, CNH...) — vieram de importação de CSV preservando
// o cabeçalho. Postgres dobra identificador sem aspas pra minúsculo, então
// aspas duplas aqui não são estilo, são obrigatórias pra bater com o nome
// real da coluna.
//
// node --env-file=.env.local scripts/build-neon-schema.mjs
import pg from "pg";

const SQL = `
create table if not exists public.pbe_veiculos_eletricos (
  id bigint primary key generated by default as identity,
  "Categoria" text,
  "Marca" text,
  "Modelo_Versao" text,
  "Propulsao" text,
  "Transmissao" text,
  "Direcao" text,
  "Combustivel" text,
  "Cidade_kmLe" numeric,
  "Estrada_kmLe" numeric,
  "Consumo_MJkm" numeric,
  "Autonomia_km" integer,
  "Class_Cat" text,
  "Class_Geral" text,
  ano_tabela integer default 2026,
  data_importacao timestamp default now(),
  codigo integer,
  ano text,
  preco numeric,
  site text,
  imagem text,
  fonte_preco text default 'Tabela Fipe',
  "Uber" boolean default false
);

create table if not exists public.pbe_motos_eletricas (
  id bigint primary key generated by default as identity,
  "Categoria" text,
  "Marca" text,
  "Modelo_Versao" text,
  "Potencia_Motor" text,
  "Capacidade_Bateria" text,
  "Autonomia_km" integer,
  "Tempo_Recarga" text,
  "Consumo_Whkm" numeric,
  "Class_Cat" text,
  "Class_Geral" text,
  ano_tabela integer default 2026,
  data_importacao timestamp default now(),
  codigo integer,
  ano text,
  preco numeric,
  site text,
  imagem text,
  fonte_preco text default 'Tabela Fipe',
  "Uber" boolean default false,
  "CNH" boolean default true
);

create table if not exists public.carregadores (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  marca text not null,
  modelo text not null,
  potencia_kw numeric,
  amperagem integer,
  voltagem text,
  fases text,
  preco_min numeric,
  preco_max numeric,
  tem_app boolean default false,
  tem_wifi boolean default false,
  tem_rfid boolean default false,
  tem_cabo boolean default false,
  descricao text,
  site_oficial text,
  imagem_url text,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  garantia_meses integer,
  eficiencia text,
  peso_kg numeric,
  dimensoes text,
  em_estoque boolean default true
);

create table if not exists public.patrocinadores_slots (
  id bigint primary key generated by default as identity,
  tipo text not null check (tipo = any (array['hero_master','banner','nativo'])),
  nome text,
  headline text,
  subtitulo text,
  cta text default 'Ver oferta',
  imagem text,
  link text,
  ativo boolean default true,
  ordem integer default 0,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  imagem_mobile text
);

create table if not exists public.eventos_cliques (
  id bigint primary key generated by default as identity,
  tipo_evento text not null,
  veiculo_id bigint,
  patrocinador_id bigint,
  detalhe text,
  pagina text,
  created_at timestamptz default now()
);

create table if not exists public.leads_propostas (
  id bigint primary key generated by default as identity,
  criado_em timestamptz not null default now(),
  nome text not null,
  whatsapp text not null,
  email text,
  cidade text,
  veiculo_id bigint,
  veiculo_marca text,
  veiculo_modelo text,
  origem text default 'comparador'
);

create table if not exists public.leads_instalacao (
  id bigint primary key generated by default as identity,
  criado_em timestamptz not null default now(),
  nome text not null,
  telefone text not null,
  cep text not null,
  tipo_imovel text not null,
  origem text default 'guia-como-escolher'
);

create table if not exists public.newsletter_leads (
  id bigint primary key generated by default as identity,
  email text not null,
  origem text,
  created_at timestamptz default now()
);

create table if not exists public.sugestoes_correcao (
  id bigint primary key generated by default as identity,
  categoria text,
  descricao text not null,
  email text,
  origem text,
  created_at timestamptz default now()
);
`;

const client = new pg.Client({ connectionString: process.env.NEON_DATABASE_URL });
await client.connect();
try {
  await client.query(SQL);
  console.log("Schema do comparaevs aplicado no Neon com sucesso.");
} finally {
  await client.end();
}
